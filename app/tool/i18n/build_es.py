# Regenerates app/lib/ui/i18n_es.dart from es_dict.py.  python3 tool/i18n/build_es.py
import os, sys
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
import es_dict
def dq(s): return '"' + s.replace('\\','\\\\').replace('"','\\"').replace('$','\\$').replace('\n','\\n') + '"'
out = ["// Spanish table. Generated by tool/i18n/build_es.py from tool/i18n/es_dict.py; edit there.",
       "// ignore_for_file: prefer_single_quotes", "part of 'i18n.dart';", "", "const Map<String, String> kEs = {"]
out += [f"  {dq(k)}: {dq(v)}," for k, v in es_dict.ES.items()]
out += ["};", "", "final List<(RegExp, String)> kEsPatterns = ["]
for a, b in es_dict.PATTERNS:
    assert "'''" not in a
    out.append(f"  (RegExp(r'''{a}'''), {dq(b)}),")
out += ["];", ""]
target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'lib', 'ui', 'i18n_es.dart')
open(target, 'w').write("\n".join(out)); print(len(es_dict.ES), 'strings,', len(es_dict.PATTERNS), 'patterns ->', target)
